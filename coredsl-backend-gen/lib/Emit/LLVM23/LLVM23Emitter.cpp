void emitLLVM23TableGen(const TargetModel &Model, llvm::raw_ostream &OS) {
  const TargetConfigModel &Config = Model.Config;
  OS << "//===-- " << Config.Namespace
     << ".td - Generated CoreDSL target -------*- tablegen -*-===//\n\n";
  OS << "include \"llvm/Target/Target.td\"\n";
  OS << "\n";
  emitRegisterInfo(Model, OS);
  OS << "\n";
  emitRegisterBanks(Model, OS);
  OS << "\n";
  emitInstructionInfo(Model, OS);
  OS << "defm : RemapAllTargetPseudoPointerOperands<" << Config.RegisterClass
     << ">;\n\n";
  OS << "def " << Config.Namespace << "InstrInfo : InstrInfo;\n";
  OS << "def " << Config.Namespace << " : Target {\n";
  OS << "  let InstructionSet = " << Config.Namespace << "InstrInfo;\n";
  OS << "}\n";
}

bool emitLLVM23Backend(const TargetModel &Model,
                       llvm::StringRef OutputDirectory,
                       llvm::raw_ostream &Errors) {
  if (llvm::sys::fs::exists(OutputDirectory)) {
    Errors << "error: output directory already exists: '" << OutputDirectory
           << "'\n";
    return false;
  }

  std::error_code EC = llvm::sys::fs::create_directories(OutputDirectory);
  if (EC) {
    Errors << "error: cannot create output directory '" << OutputDirectory
           << "': " << EC.message() << '\n';
    return false;
  }
  auto appendPath = [](llvm::StringRef Directory, llvm::StringRef Name) {
    llvm::SmallString<256> Result(Directory);
    llvm::sys::path::append(Result, Name);
    return Result.str().str();
  };
  const std::string TargetInfoDirectory =
      appendPath(OutputDirectory, "TargetInfo");
  if ((EC = llvm::sys::fs::create_directories(TargetInfoDirectory))) {
    Errors << "error: cannot create TargetInfo directory: " << EC.message()
           << '\n';
    return false;
  }

  const std::string &NS = Model.Config.Namespace;
  auto path = [&](llvm::StringRef Name) {
    return appendPath(OutputDirectory, Name);
  };
  auto targetInfoPath = [&](llvm::StringRef Name) {
    return appendPath(TargetInfoDirectory, Name);
  };
  return writeFile(
             path("CMakeLists.txt"),
             [&](llvm::raw_ostream &OS) { emitCMakeLists(Model, OS); },
             Errors) &&
         writeFile(
             path(NS + ".td"),
             [&](llvm::raw_ostream &OS) { emitLLVM23TableGen(Model, OS); },
             Errors) &&
         writeFile(
             path(NS + "Target.cpp"),
             [&](llvm::raw_ostream &OS) { emitTargetSource(Model, OS); },
             Errors) &&
         writeFile(
             targetInfoPath("CMakeLists.txt"),
             [&](llvm::raw_ostream &OS) { emitTargetInfoCMake(Model, OS); },
             Errors) &&
         writeFile(
             targetInfoPath(NS + "TargetInfo.h"),
             [&](llvm::raw_ostream &OS) { emitTargetInfoHeader(Model, OS); },
             Errors) &&
         writeFile(
             targetInfoPath(NS + "TargetInfo.cpp"),
             [&](llvm::raw_ostream &OS) { emitTargetInfoSource(Model, OS); },
             Errors);
}

