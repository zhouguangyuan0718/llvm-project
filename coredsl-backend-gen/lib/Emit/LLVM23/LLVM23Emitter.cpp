bool isScalarRuleSupported(const TargetModel &Model,
                           const InstructionModel &Instruction) {
  if (!Instruction.SelectionRule)
    return false;
  const ValueTypeModel &Type =
      Instruction.Operands[Instruction.SelectionRule->OutputOperand].Type;
  return Type.K == ValueTypeModel::Kind::ScalarInteger &&
         Type.ScalarBits == Model.Config.RegisterWidth;
}

void emitInstructionInfo(const TargetModel &Model, llvm::raw_ostream &OS) {
  const TargetConfigModel &Config = Model.Config;
  OS << "// Generated by coredsl-backend-gen. Do not edit.\n\n";
  OS << "class " << Config.Namespace
     << "Inst<dag outs, dag ins, string asmstr> : Instruction {\n";
  OS << "  let Namespace = \"" << Config.Namespace << "\";\n";
  OS << "  let OutOperandList = outs;\n";
  OS << "  let InOperandList = ins;\n";
  OS << "  let AsmString = asmstr;\n";
  OS << "  let Pattern = [];\n";
  OS << "  let isPseudo = 1;\n";
  OS << "  let hasSideEffects = 0;\n";
  OS << "}\n\n";
  OS << "def COREDSL_RET : " << Config.Namespace
     << "Inst<(outs), (ins), \"RET\"> {\n";
  OS << "  let isReturn = 1;\n";
  OS << "  let isTerminator = 1;\n";
  OS << "  let isBarrier = 1;\n";
  OS << "}\n\n";
  for (const InstructionModel &Instruction : Model.Instructions) {
    if (!isScalarRuleSupported(Model, Instruction)) {
      OS << "// Not emitted: " << Instruction.Name
         << " has no supported scalar GlobalISel selection rule.\n";
      continue;
    }
    const SelectionRuleModel &Rule = *Instruction.SelectionRule;
    const OperandModel &Output = Instruction.Operands[Rule.OutputOperand];
    const OperandModel &LHS = Instruction.Operands[Rule.LHSOperand];
    const OperandModel &RHS = Instruction.Operands[Rule.RHSOperand];
    const std::string Type = Output.Type.tableGenType();
    OS << "def " << Instruction.Name << " : " << Config.Namespace << "Inst<"
       << "(outs " << Config.RegisterClass << ":$" << Output.Name << "), "
       << "(ins " << Config.RegisterClass << ":$" << LHS.Name << ", "
       << Config.RegisterClass << ":$" << RHS.Name << "), \""
       << Instruction.Name << " $" << Output.Name << ", $" << LHS.Name << ", $"
       << RHS.Name << "\">;\n\n";
    OS << "def : Pat<(" << Type << " (" << tableGenOperator(Rule.Opcode) << " ("
       << Type << " " << Config.RegisterClass << ":$" << LHS.Name << "), ("
       << Type << " " << Config.RegisterClass << ":$" << RHS.Name << "))), ("
       << Instruction.Name << " " << Config.RegisterClass << ":$" << LHS.Name
       << ", " << Config.RegisterClass << ":$" << RHS.Name << ")>;\n\n";
  }
}

using FileEmitter = std::function<void(llvm::raw_ostream &)>;

bool writeFile(llvm::StringRef Path, const FileEmitter &Emit,
               llvm::raw_ostream &Errors) {
  std::error_code EC;
  llvm::raw_fd_ostream OS(Path, EC, llvm::sys::fs::OF_Text);
  if (EC) {
    Errors << "error: cannot write '" << Path << "': " << EC.message() << '\n';
    return false;
  }
  Emit(OS);
  return true;
}

